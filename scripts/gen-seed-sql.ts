// Writes supabase/seed.sql from the question bank. Run: npm run gen:seed-sql
import { writeFileSync } from "node:fs";
import { QUESTIONS } from "../lib/questions";

const lit = (s: string | undefined) => (s === undefined ? "null" : `'${s.replace(/'/g, "''")}'`);

const rows = QUESTIONS.map(
  (q) =>
    `(${lit(q.id)}, ${lit(q.subject)}, ${lit(q.topic)}, ${q.difficulty}, ${lit(q.prompt)}, ${lit(JSON.stringify(q.options))}::jsonb, ${q.answer}, ${lit(q.solution)}, ${lit(q.commonMistake)})`,
);

const sql = `-- Generated by scripts/gen-seed-sql.ts. Do not edit by hand.
insert into public.questions (id, subject, topic, difficulty, prompt, options, answer, solution, common_mistake) values
${rows.join(",\n")}
on conflict (id) do update set
  subject = excluded.subject, topic = excluded.topic, difficulty = excluded.difficulty,
  prompt = excluded.prompt, options = excluded.options, answer = excluded.answer,
  solution = excluded.solution, common_mistake = excluded.common_mistake;
`;
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log(`Wrote ${QUESTIONS.length} questions to supabase/seed.sql`);
